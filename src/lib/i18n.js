function pad(n) {
  return String(n).padStart(2, '0');
}

function monthName(month) {
  return MONTHS[Math.max(0, Math.min(11, Number(month) - 1))];
}

function translateDates(input) {
  let value = input;
  value = value.replace(
    /(\d{4})年(\d{1,2})月(\d{1,2})日\s*[–-]\s*(\d{1,2})日/g,
    (_match, year, month, day, end) => `${monthName(month)} ${Number(day)}–${Number(end)}, ${year}`,
  );
  value = value.replace(
    /(\d{4})年(\d{1,2})月(\d{1,2})日/g,
    (_match, year, month, day) => `${monthName(month)} ${Number(day)}, ${year}`,
  );
  value = value.replace(
    /(\d{1,2})月(\d{1,2})日\s*[–-]\s*(\d{1,2})日/g,
    (_match, month, day, end) => `${monthName(month)} ${Number(day)}–${Number(end)}`,
  );
  value = value.replace(
    /(\d{1,2})月(\d{1,2})日/g,
    (_match, month, day) => `${monthName(month)} ${Number(day)}`,
  );
  value = value.replace(/星期([一二三四五六日])/g, (_match, day) => WEEKDAYS[day] || '');
  return value;
}

function plural(n, one, many) {
  return `${n} ${Number(n) === 1 ? one : many}`;
}

function translatePatterns(input) {
  let value = translateDates(input);
  value = value.replace(/(\d+)\s*段已飞/g, (_match, n) => `${n}/${'flown'}`);
  value = value.replace(/(\d+)\s*段/g, (_match, n) => plural(n, 'leg', 'legs'));
  value = value.replace(/(\d+)\s*次/g, (_match, n) => plural(n, 'session', 'sessions'));
  value = value.replace(/(\d+)\s*个航点/g, (_match, n) => plural(n, 'waypoint', 'waypoints'));
  value = value.replace(/(\d+)\s*小时\s*(\d+)\s*分/g, (_match, h, m) => `${h} h ${m} min`);
  value = value.replace(/(\d+)\s*小时/g, (_match, h) => `${h} h`);
  value = value.replace(/(\d+)\s*分钟/g, (_match, m) => `${m} min`);
  value = value.replace(/(\d+)\s*人/g, (_match, n) => `${n} pax`);
  value = value.replace(/\s*([·/])\s*/g, ' $1 ');
  value = value.replace(/[ \t]{2,}/g, ' ');
  return value.trim() === input.trim() ? value : value;
}

const PHRASES = Object.entries(EN).sort((a, b) => b[0].length - a[0].length);

export function getLanguage() {
  return language;
}

export function t(zh, en) {
  return language === 'en' ? en : zh;
}

export function translateText(input) {
  const source = String(input ?? '');
  if (language !== 'en' || !CJK.test(source)) return source;
  const trimmed = source.trim();
  if (!trimmed) return source;
  const exact = EN[trimmed];
  if (exact) {
    const leading = source.slice(0, source.indexOf(trimmed));
    const trailing = source.slice(source.indexOf(trimmed) + trimmed.length);
    return `${leading}${exact}${trailing}`;
  }
  let value = translatePatterns(source);
  for (const [zh, en] of PHRASES) {
    if (value.includes(zh)) value = value.split(zh).join(en);
  }
  return value;
}

function shouldSkip(parent) {
  if (!parent || !parent.closest) return false;
  return Boolean(parent.closest('script, style, textarea, input, .no-i18n, [data-i18n-skip]'));
}

export function applyTranslations(root = document.body) {
  if (!root || language !== 'en') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !CJK.test(node.nodeValue)) return NodeFilter.FILTER_REJECT;
      if (shouldSkip(node.parentElement)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const current = node.nodeValue;
    const previous = originals.get(node);
    if (!previous || CJK.test(current)) originals.set(node, current);
    const translated = translateText(current);
    if (translated !== current) node.nodeValue = translated;
  }
  for (const element of root.querySelectorAll('[placeholder], [title], [aria-label]')) {
    if (element.closest('.no-i18n, script, style')) continue;
    const store = attributeOriginals.get(element) || {};
    for (const attr of ['placeholder', 'title', 'aria-label']) {
      if (!element.hasAttribute(attr)) continue;
      const current = element.getAttribute(attr);
      if (CJK.test(current)) store[attr] = current;
      if (CJK.test(current)) element.setAttribute(attr, translateText(current));
    }
    attributeOriginals.set(element, store);
  }
}

function restoreTranslations(root = document.body) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const previous = originals.get(node);
    if (previous && !CJK.test(node.nodeValue)) node.nodeValue = previous;
  }
  for (const element of root.querySelectorAll('[placeholder], [title], [aria-label]')) {
    const store = attributeOriginals.get(element);
    if (!store) continue;
    for (const [attr, value] of Object.entries(store)) {
      if (element.hasAttribute(attr)) element.setAttribute(attr, value);
    }
  }
}

function scheduleApply() {
  if (scheduled) return;
  scheduled = true;
  requestAnimationFrame(() => {
    scheduled = false;
    applyTranslations();
  });
}

export function setLanguage(next) {
  const value = next === 'en' ? 'en' : 'zh';
  if (value === language) {
    if (value === 'en') scheduleApply();
    return;
  }
  restoreTranslations();
  language = value;
  document.documentElement.lang = value === 'en' ? 'en' : 'zh-CN';
  document.documentElement.classList.toggle('lang-en', value === 'en');
  if (value === 'en') scheduleApply();
}

export function startTranslationObserver() {
  if (observer || typeof document === 'undefined') return;
  observer = new MutationObserver(() => {
    if (language === 'en') scheduleApply();
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['placeholder', 'title', 'aria-label'],
  });
}
